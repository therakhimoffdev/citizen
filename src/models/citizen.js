const mongoose = require('mongoose');

const citizenSchema = new mongoose.Schema({
  telegramId: {
    type: String,
    required: true,
    unique: true,
    index: true
  },
  username: {
    type: String,
    default: ''
  },
  firstName: {
    type: String,
    default: ''
  },
  lastName: {
    type: String,
    default: ''
  },
  language: {
    type: String,
    enum: ['uz', 'ru', 'en'],
    default: 'uz'
  },
  phone: {
    type: String,
    default: ''
  },
  notificationEnabled: {
    type: Boolean,
    default: true
  },
  createdAt: {
    type: Date,
    default: Date.now
  },
  updatedAt: {
    type: Date,
    default: Date.now
  }
}, {
  timestamps: true
});

module.exports = mongoose.model('Citizen', citizenSchema);
